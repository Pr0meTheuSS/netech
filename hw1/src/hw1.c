/*
 * hw-1: разбор и форматирование MAC-адресов, контрольная сумма IPv4.
 * Реализация по контракту include/hw1.h.
 */
#include "hw1.h"

/* ------------------------------------------------------------------ */
/* parse_mac                                                           */
/* ------------------------------------------------------------------ */

/* Значение одной hex-цифры: 0..15, или -1, если символ не hex-цифра. */
static int hex_val(int c) {
  if (c >= '0' && c <= '9')
    return c - '0';
  if (c >= 'a' && c <= 'f')
    return c - 'a' + 10;
  if (c >= 'A' && c <= 'F')
    return c - 'A' + 10;
  return -1;
}

int parse_mac(const char *str, uint8_t out[6]) {
  if (str == NULL || out == NULL)
    return -1;

  /*
   * MAC-адрес: 6 групп по две hex-цифры, группы разделены символом
   * ':' или '-' (в каждой позиции допустим любой из двух, можно
   * вперемешку). Корректная строка имеет длину ровно 17:
   *
   *     индекс:  0 1 2  3 4 5  6 7 8  ...  14  15 16 17
   *             [A A] : [B B] : [C C] :  :  [F F] \0
   *
   * Группа i занимает позиции 3i и 3i+1, разделитель после неё —
   * позиция 3i+2 (для i < 5).
   */
  for (int i = 0; i < 6; i++) {
    /* Старшую цифру проверяем ДО чтения младшей: если на позиции 3i
     * уже стоит '\0', то позиция 3i+1 лежит за пределами строки, и
     * её чтение было бы выходом за границы объекта (ловится ASan). */
    int hi = hex_val((unsigned char)str[3 * i]);
    if (hi < 0)
      return -1; /* не hex-цифра; '\0' — строка кончилась раньше */

    int lo = hex_val((unsigned char)str[3 * i + 1]);
    if (lo < 0)
      return -1; /* не hex-цифра; '\0' — обрезанная группа */

    out[i] = (uint8_t)((hi << 4) | lo);

    if (i < 5) { /* разделитель только между группами */
      char sep = str[3 * i + 2];
      if (sep != ':' && sep != '-')
        return -1;
    }
  }

  /* Шестая группа прочитана: после неё строка должна закончиться.
   * Иначе в хвосте лишние символы ("...:FF:00", "...:FF\n" и т.п.).
   * str[17] читать безопасно: если строка короче — до этой проверки
   * мы бы не дошли; если длиннее — это символ внутри строки. */
  if (str[17] != '\0')
    return -1;

  return 0;
}

/* ------------------------------------------------------------------ */
/* format_mac                                                          */
/* ------------------------------------------------------------------ */

void format_mac(const uint8_t mac[6], char *out) {
  static const char digits[] = "0123456789ABCDEF";

  /* Контракт требует валидные буферы (out >= 18 байт); проверка —
   * просто защита от неопределённого поведения. */
  if (mac == NULL || out == NULL)
    return;

  for (int i = 0; i < 6; i++) {
    out[3 * i] = digits[mac[i] >> 4];       /* старшая тетрада  */
    out[3 * i + 1] = digits[mac[i] & 0x0F]; /* младшая тетрада  */
    if (i < 5)
      out[3 * i + 2] = ':';
  }
  out[17] = '\0';
}

/* ------------------------------------------------------------------ */
/* ipv4_checksum (RFC 1071)                                            */
/* ------------------------------------------------------------------ */

uint16_t ipv4_checksum(const uint8_t *hdr, size_t len) {
  /* 32 бита хватает с запасом: даже без свёртки в цикле сумма
   * короткого буфера не переполняет uint32_t. */
  uint32_t sum = 0;

  /* Суммируем 16-битные слова в сетевом порядке байт (big-endian):
   * первый байт пары — старший. Поле checksum по контракту уже
   * обнулено в переданном буфере, отдельно обрабатывать его не нужно. */
  for (size_t i = 0; i + 1 < len; i += 2)
    sum += ((uint32_t)hdr[i] << 8) | hdr[i + 1];

  /* Нечётная длина: последний байт считается старшим байтом слова,
   * младший байт дополняется нулём (требование скрытых тестов). */
  if ((len & 1u) != 0)
    sum += (uint32_t)hdr[len - 1] << 8;

  /* Свёртка переносов: пока есть биты выше 16-го, добавляем их
   * к младшим 16 битам (арифметика дополнения до единицы). */
  while ((sum >> 16) != 0)
    sum = (sum & 0xFFFFu) + (sum >> 16);

  /* Дополнение до единицы. Инвариант: сумма заголовка с уже
   * вписанной верной контрольной суммой даёт 0x0000. */
  return (uint16_t)(~sum & 0xFFFFu);
}
